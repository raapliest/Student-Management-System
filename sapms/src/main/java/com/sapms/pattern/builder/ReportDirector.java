package com.sapms.pattern.builder;

import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.stereotype.Component;
import java.util.*;

/**
 * DESIGN PATTERN: Builder — Director
 * Knows how to use the Builder to construct common report types.
 * Separates the construction process from representation.
 */
@Component
public class ReportDirector {

    @Autowired
    private JdbcTemplate jdbc;

    /** Build a full admin system report */
    public AcademicReport buildAdminReport(String generatedBy) {
        int totalStudents = jdbc.queryForObject("SELECT COUNT(*) FROM student", Integer.class);
        int totalCourses  = jdbc.queryForObject("SELECT COUNT(*) FROM course", Integer.class);
        int passing       = jdbc.queryForObject("SELECT COUNT(*) FROM grade WHERE status='PASS'", Integer.class);
        int failing       = jdbc.queryForObject("SELECT COUNT(*) FROM grade WHERE status='FAIL'", Integer.class);
        int atRisk        = jdbc.queryForObject("SELECT COUNT(*) FROM grade WHERE status='AT_RISK'", Integer.class);

        Map<String, Object> summary = new LinkedHashMap<>();
        summary.put("totalStudents", totalStudents);
        summary.put("totalCourses",  totalCourses);
        summary.put("passing",       passing);
        summary.put("failing",       failing);
        summary.put("atRisk",        atRisk);

        List<Map<String, Object>> courseStats = jdbc.queryForList(
            "SELECT c.course_code, c.course_name, " +
            "COUNT(g.id) as total, " +
            "SUM(CASE WHEN g.status='PASS' THEN 1 ELSE 0 END) as passing, " +
            "SUM(CASE WHEN g.status='FAIL' THEN 1 ELSE 0 END) as failing, " +
            "ROUND(AVG(g.total_score),2) as avg_score " +
            "FROM course c LEFT JOIN grade g ON c.id=g.course_id GROUP BY c.id");

        String yearLabel = "";
        try {
            yearLabel = jdbc.queryForObject(
                "SELECT year_label FROM academic_year WHERE is_active=1 LIMIT 1", String.class);
        } catch (Exception ignored) {}

        return new AcademicReport.Builder("System Academic Performance Report", generatedBy)
            .academicYear(yearLabel)
            .summary(summary)
            .courseStats(courseStats)
            .includeCharts(true)
            .notes("Auto-generated by SAPMS Report Director")
            .build();
    }

    /** Build a lightweight student transcript */
    public AcademicReport buildStudentTranscript(String studentNo, String generatedBy) {
        List<Map<String, Object>> grades = jdbc.queryForList(
            "SELECT c.course_code, c.course_name, c.credit_hours, " +
            "g.total_score, g.grade_letter, g.status " +
            "FROM grade g JOIN course c ON g.course_id=c.id " +
            "WHERE g.student_no=? ORDER BY c.course_code", studentNo);

        Map<String, Object> summary = new LinkedHashMap<>();
        summary.put("studentNo", studentNo);
        summary.put("totalCourses", grades.size());
        double avg = grades.stream()
            .filter(r -> r.get("total_score") != null)
            .mapToDouble(r -> Double.parseDouble(r.get("total_score").toString()))
            .average().orElse(0.0);
        summary.put("averageScore", Math.round(avg * 100) / 100.0);

        return new AcademicReport.Builder("Student Academic Transcript", generatedBy)
            .summary(summary)
            .studentDetails(grades)
            .includeCharts(false)
            .build();
    }
}
